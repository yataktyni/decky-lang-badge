/**
 * Resolves the best UI language code from Steam Deck locale.
 */
export function getSupportedLanguage(rawLocale?: string): string {
  try {
    const locale = (
      rawLocale ??
      (typeof navigator !== "undefined" ? navigator.language : "") ??
      ""
    )
      .trim()
      .replace(/_/g, "-");

    if (!locale) return "en";
    const lower = locale.toLowerCase();

    if (lower === "pt-br") return "pt-BR";
    if (lower.startsWith("zh-tw") || lower.startsWith("zh-hk") || lower.includes("hant")) return "zh-TW";
    if (lower.startsWith("zh")) return "zh-CN";
    if (lower.startsWith("es-")) return detectLanguageFromLocale(lower).code;
    if (lower.startsWith("nb") || lower.startsWith("nn")) return "no";

    const base = lower.split("-")[0];
    if (translations[base]) return base;
    return "en";
  } catch {
    return "en";
  }
}

/**
 * Resolves the active UI language based on targetLanguage setting:
 * - Explicit targetLanguage (not "auto") -> UI switches to that language directly
 * - "auto" -> uses Steam Deck UI language (e.g. uk, pl, de, ja, or en fallback)
 */
export function resolveUiLanguage(
  targetSetting: TargetLanguageSetting | string | undefined,
  resolvedTargetLang: LanguageConfig,
  rawLocale?: string
): string {
  if (targetSetting && targetSetting !== "auto") {
    return translations[resolvedTargetLang.code] ? resolvedTargetLang.code : "en";
  }
  return getSupportedLanguage(rawLocale);
}

/**
 * Translates a key to the specified language, falling back to English.
 */
export function t(key: string, lang: string = "en"): string {
  const exact = translations[lang]?.[key];
  if (exact) return exact;

  const base = lang.toLowerCase().split("-")[0];
  const baseMatch = translations[base]?.[key];
  if (baseMatch) return baseMatch;

  return translations["en"]?.[key] ?? key;
}
